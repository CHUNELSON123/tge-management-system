import test from "node:test";
import assert from "node:assert/strict";
import bcrypt from "bcrypt";
import dotenv from "dotenv";
import express from "express";
import { createServer } from "node:http";
import { once } from "node:events";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
import { prisma } from "database";
import { LoginUseCase } from "./application/use-cases/login.usecase.js";
import { PrismaUserRepository } from "./infrastructure/repositories/prisma-user.repository.js";
import { JwtService } from "../../common/services/jwt.service.js";
import { createAuthRouter } from "./presentation/controllers/auth.controller.js";
import { authenticate } from "../../common/middleware/authenticate.middleware.js";
import { requirePermission } from "../../common/middleware/require-role.middleware.js";

test("database-backed login, restored session and logout invalidation", async () => {
  dotenv.config({ path: resolve(process.cwd(), ".env") });
  if (!process.env.JWT_SECRET) throw new Error("Set JWT_SECRET in server/.env before running auth integration tests.");
  const roleName = `Auth Test ${Date.now()}`;
  const email = `auth-test-${Date.now()}@example.org`;
  const role = await prisma.role.create({ data: { name: roleName } });
  const userManagement = await prisma.permission.upsert({ where: { code: "users.manage" }, update: {}, create: { code: "users.manage", description: "Manage accounts" } });
  const passwordHash = await bcrypt.hash("auth-test-password", 4);
  const user = await prisma.user.create({ data: { roleId: role.id, email, passwordHash, firstName: "Auth", lastName: "Test", status: "ACTIVE", emailVerifiedAt: new Date() } });
  const app = express(); app.use(express.json());
  app.get("/admin-check", authenticate, requirePermission("users.manage"), (_req,res)=>res.status(200).json({ ok: true }));
  let emailHtml = "";
  app.use("/api/auth", createAuthRouter(new LoginUseCase(new PrismaUserRepository(), new JwtService()), { sendEmail: async ({ html }: { html: string }) => { emailHtml = html; } } as never));
  const server = createServer(app); server.listen(0); await once(server, "listening");
  const address = server.address(); if (!address || typeof address === "string") throw new Error("Test server did not bind.");
  const base = `http://127.0.0.1:${address.port}/api/auth`;
  try {
    const login = await fetch(`${base}/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password: "auth-test-password" }) });
    assert.equal(login.status, 200);
    const loginBody = await login.clone().text();
    assert.equal(loginBody.includes("passwordHash"), false);
    assert.equal(loginBody.includes(passwordHash), false);
    const { data } = await login.json() as { data: { accessToken: string } };
    const malformedSession = await fetch(`${base}/session`, { headers: { Authorization: "Bearer invalid-token" } });
    assert.equal(malformedSession.status, 401);
    const session = await fetch(`${base}/session`, { headers: { Authorization: `Bearer ${data.accessToken}` } });
    assert.equal(session.status, 200);
    await prisma.user.update({ where: { id: user.id }, data: { status: "SUSPENDED" } });
    const suspendedLogin = await fetch(`${base}/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password: "auth-test-password" }) });
    assert.equal(suspendedLogin.status, 401);
    const suspendedSession = await fetch(`${base}/session`, { headers: { Authorization: `Bearer ${data.accessToken}` } });
    assert.equal(suspendedSession.status, 401);
    await prisma.user.update({ where: { id: user.id }, data: { status: "ACTIVE" } });
    const deniedRole = await fetch(`http://127.0.0.1:${address.port}/admin-check`, { headers: { Authorization: `Bearer ${data.accessToken}` } });
    assert.equal(deniedRole.status, 403);
    await prisma.rolePermission.create({ data: { roleId: role.id, permissionId: userManagement.id } });
    const grantedRole = await fetch(`http://127.0.0.1:${address.port}/admin-check`, { headers: { Authorization: `Bearer ${data.accessToken}` } });
    assert.equal(grantedRole.status, 200);
    const changed = await fetch(`${base}/password/change`, { method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${data.accessToken}` }, body: JSON.stringify({ currentPassword: "auth-test-password", newPassword: "changed-password" }) });
    assert.equal(changed.status, 200);
    const wrongCurrentPassword = await fetch(`${base}/password/change`, { method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${data.accessToken}` }, body: JSON.stringify({ currentPassword: "wrong-current", newPassword: "another-password" }) });
    assert.equal(wrongCurrentPassword.status, 400);
    const oldPassword = await fetch(`${base}/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password: "auth-test-password" }) });
    assert.equal(oldPassword.status, 401);
    const requestReset = await fetch(`${base}/password/recovery`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email }) });
    assert.equal(requestReset.status, 202);
    const requestUnknown = await fetch(`${base}/password/recovery`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email: `missing-${Date.now()}@example.org` }) });
    assert.equal(requestUnknown.status, 202);
    assert.deepEqual(await requestUnknown.json(), await requestReset.clone().json());
    const resetUrl = emailHtml.match(/href="([^"]*reset-password[^"]*)"/)?.[1];
    assert.ok(resetUrl);
    const resetToken = new URL(resetUrl).searchParams.get("token");
    assert.ok(resetToken);
    const storedResetToken = await prisma.passwordResetToken.findUnique({ where: { tokenHash: createHash("sha256").update(resetToken).digest("hex") } });
    assert.ok(storedResetToken);
    assert.notEqual(storedResetToken.tokenHash, resetToken);
    const reset = await fetch(`${base}/password/reset`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ token: resetToken, password: "reset-password" }) });
    assert.equal(reset.status, 200);
    const reusedReset = await fetch(`${base}/password/reset`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ token: resetToken, password: "another-password" }) });
    assert.equal(reusedReset.status, 400);
    const expiryRequest = await fetch(`${base}/password/recovery`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email }) });
    assert.equal(expiryRequest.status, 202);
    const expiredUrl = emailHtml.match(/href="([^"]*reset-password[^"]*)"/)?.[1];
    assert.ok(expiredUrl);
    const expiredToken = new URL(expiredUrl).searchParams.get("token");
    assert.ok(expiredToken);
    await prisma.passwordResetToken.update({ where: { tokenHash: createHash("sha256").update(expiredToken).digest("hex") }, data: { expiresAt: new Date(Date.now() - 1000) } });
    const expiredReset = await fetch(`${base}/password/reset`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ token: expiredToken, password: "expired-password" }) });
    assert.equal(expiredReset.status, 400);
    const relogin = await fetch(`${base}/login`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password: "reset-password" }) });
    assert.equal(relogin.status, 200);
    const { data: renewed } = await relogin.json() as { data: { accessToken: string } };
    const logout = await fetch(`${base}/logout`, { method: "POST", headers: { Authorization: `Bearer ${renewed.accessToken}` } });
    assert.equal(logout.status, 200);
    const rejected = await fetch(`${base}/session`, { headers: { Authorization: `Bearer ${renewed.accessToken}` } });
    assert.equal(rejected.status, 401);
    const auditActions = await prisma.auditLog.findMany({ where: { actorUserId: user.id }, select: { action: true, details: true } });
    for (const action of ["AUTH_LOGIN_SUCCESS", "AUTH_PASSWORD_CHANGED", "AUTH_PASSWORD_RESET", "AUTH_LOGOUT"]) {
      assert.ok(auditActions.some((record) => record.action === action), `Expected ${action} audit record.`);
    }
    const failedLoginAudit = await prisma.auditLog.findFirst({ where: { action: "AUTH_LOGIN_FAILURE", entityType: "Authentication" } });
    assert.ok(failedLoginAudit);
    assert.equal(JSON.stringify(auditActions).includes(passwordHash), false);
    assert.equal(JSON.stringify(auditActions).includes(data.accessToken), false);
  } finally {
    server.close();
    await prisma.user.delete({ where: { id: user.id } });
    await prisma.role.delete({ where: { id: role.id } });
    await prisma.$disconnect();
  }
});
