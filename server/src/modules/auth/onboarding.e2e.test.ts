import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID, createHash } from "node:crypto";
import { createServer } from "node:http";
import { once } from "node:events";
import { resolve } from "node:path";
import bcrypt from "bcrypt";
import dotenv from "dotenv";
import express from "express";
import { prisma } from "database";
import { JwtService } from "../../common/services/jwt.service.js";
import { CreateMembershipApplicationUseCase } from "./application/use-cases/create-membership-application.usecase.js";
import { ActivateAccountUseCase } from "./application/use-cases/activate-account.usecase.js";
import { CreateAccountActivationTokenUseCase } from "./application/use-cases/create-account-activation-token.usecase.js";
import { CreateAccountUseCase } from "./application/use-cases/create-account.usecase.js";
import { ResendAccountInvitationUseCase } from "./application/use-cases/resend-account-invitation.usecase.js";
import { LoginUseCase } from "./application/use-cases/login.usecase.js";
import { PrismaMembershipApplicationRepository } from "./infrastructure/repositories/prisma-membership-application.repository.js";
import { PrismaAccountActivationTokenRepository } from "./infrastructure/repositories/prisma-account-activation-token.repository.js";
import { PrismaUserRepository } from "./infrastructure/repositories/prisma-user.repository.js";
import { createMembershipApplicationRouter } from "./presentation/controllers/membership-application.controller.js";
import { createAccountRouter } from "./presentation/controllers/account.controller.js";
import { createAuthRouter } from "./presentation/controllers/auth.controller.js";
import { PrismaAdminMembersRepository } from "../admin-portal/infrastructure/prisma-admin-members.repository.js";
import { GetAdminMembersUseCase } from "../admin-portal/application/get-admin-members.usecase.js";
import { RegisterAdminMemberUseCase } from "../admin-portal/application/register-admin-member.usecase.js";
import { ReviewMembershipApplicationUseCase } from "../admin-portal/application/review-membership-application.usecase.js";
import { createAdminMembersRouter } from "../admin-portal/presentation/controllers/admin-members.controller.js";

test("membership and invited accounts complete onboarding with recoverable email failures", async () => {
  dotenv.config({ path: resolve(process.cwd(), ".env") });
  const oldActivationUrl = process.env.ACTIVATION_URL;
  process.env.ACTIVATION_URL = "https://example.test/activate-account";
  const suffix = randomUUID();
  const email = (name: string) => `onboarding-${name}-${suffix}@example.test`;
  const emails = ["admin", "applicant", "rejected", "direct", "mentor", "suspended"].map(email);
  const [adminRole, mentorRole] = await Promise.all([
    prisma.role.findFirstOrThrow({ where: { name: "System Administrator" } }),
    prisma.role.findFirstOrThrow({ where: { name: "Mentor" } }),
  ]);
  const admin = await prisma.user.create({ data: { roleId: adminRole.id, email: email("admin"), firstName: "Test", lastName: "Admin", passwordHash: await bcrypt.hash("test-password", 4), status: "ACTIVE", emailVerifiedAt: new Date() } });
  let mail: { to: string; html: string }[] = [];
  let failMail = false;
  const mailer = { sendEmail: async (message: { to: string; html: string }) => { if (failMail) throw new Error("simulated delivery failure"); mail.push(message); } } as never;
  const users = new PrismaUserRepository();
  const tokens = new PrismaAccountActivationTokenRepository();
  const createToken = new CreateAccountActivationTokenUseCase(tokens);
  const members = new PrismaAdminMembersRepository();
  const app = express(); app.use(express.json());
  app.use("/applications", createMembershipApplicationRouter(new CreateMembershipApplicationUseCase(new PrismaMembershipApplicationRepository(), async () => true), new ActivateAccountUseCase(tokens)));
  app.use("/auth", createAuthRouter(new LoginUseCase(users, new JwtService()), mailer));
  app.use("/accounts", createAccountRouter(new CreateAccountUseCase(users, createToken, mailer), new ResendAccountInvitationUseCase(users, createToken, mailer), createToken));
  app.use("/admin", createAdminMembersRouter(new GetAdminMembersUseCase(members), new RegisterAdminMemberUseCase(members, createToken, mailer), new ReviewMembershipApplicationUseCase(members, createToken, mailer)));
  const server = createServer(app); server.listen(0); await once(server, "listening");
  const address = server.address(); if (!address || typeof address === "string") throw new Error("Test server did not bind");
  const base = `http://127.0.0.1:${address.port}`;
  let accessToken = "";
  const post = (path: string, body: object, authenticated = false) => fetch(base + path, { method: "POST", headers: { "Content-Type": "application/json", ...(authenticated ? { Authorization: `Bearer ${accessToken}` } : {}) }, body: JSON.stringify(body) });
  const invitation = (recipient: string) => {
    const message = mail.filter((item) => item.to === recipient).at(-1);
    const url = message?.html.match(/href="([^"]+)"/)?.[1];
    assert.ok(url, `Expected an invitation for ${recipient}`);
    const token = new URL(url).searchParams.get("token"); assert.ok(token); return token;
  };
  const person = (name: string) => ({ firstName: "Test", lastName: name, email: email(name) });
  const application = (name: string) => ({ ...person(name), phone: "+14185551234", location: "Quebec City, Canada", dateOfBirth: "1990-01-01", gender: "Prefer not to say", nationality: "Canada", bio: "Interested in sustainable entrepreneurship." });
  try {
    const login = await post("/auth/login", { email: admin.email, password: "test-password" }); assert.equal(login.status, 200);
    accessToken = ((await login.json()) as { data: { accessToken: string } }).data.accessToken;
    assert.equal((await post("/applications", application("applicant"))).status, 201);
    assert.equal((await post("/applications", application("applicant"))).status, 201);
    const applications = await prisma.membershipApplication.findMany({ where: { applicantEmail: email("applicant") } });
    assert.equal(applications.length, 1); assert.equal(applications[0].status, "PENDING");
    assert.equal(await prisma.user.count({ where: { email: email("applicant") } }), 0);
    const approval = await post(`/admin/members/applications/${applications[0].id}/approve`, {}, true);
    assert.equal(approval.status, 200, await approval.clone().text());
    assert.equal(((await approval.json()) as { data: { invitationSent: boolean } }).data.invitationSent, true);
    const member = await prisma.user.findUniqueOrThrow({ where: { email: email("applicant") }, include: { memberProfile: true, role: true } });
    assert.equal(member.status, "PENDING_ACTIVATION"); assert.equal(member.role.name, "Member"); assert.ok(member.memberProfile);
    const token = invitation(member.email);
    const stored = await prisma.accountActivationToken.findUnique({ where: { tokenHash: createHash("sha256").update(token).digest("hex") } }); assert.ok(stored);
    assert.equal((await post("/applications/activate", { token, password: "test-password" })).status, 200);
    assert.equal((await post("/applications/activate", { token, password: "test-password" })).status, 400);
    assert.equal((await post("/auth/login", { email: member.email, password: "test-password" })).status, 200);
    assert.equal((await post(`/admin/members/applications/${applications[0].id}/approve`, {}, true)).status, 409);
    assert.equal((await post("/applications", application("rejected"))).status, 201);
    const rejected = await prisma.membershipApplication.findFirstOrThrow({ where: { applicantEmail: email("rejected") } });
    assert.equal((await post(`/admin/members/applications/${rejected.id}/reject`, { reason: "Please update your information" }, true)).status, 200);
    assert.equal(await prisma.user.count({ where: { email: email("rejected") } }), 0);
    assert.equal((await post("/applications", application("rejected"))).status, 201);
    assert.equal(await prisma.membershipApplication.count({ where: { applicantEmail: email("rejected") } }), 2);
    failMail = true;
    assert.equal((await post("/admin/members", person("direct"), true)).status, 400);
    const direct = await post("/admin/members", { ...person("direct"), phone: "+14185551234", location: "Quebec City, Canada", dateOfBirth: "1990-01-01", gender: "Prefer not to say", nationality: "Canada", bio: "Interested in sustainable entrepreneurship." }, true);
    assert.equal(direct.status, 201, await direct.clone().text());
    assert.equal(((await direct.json()) as { data: { invitationSent: boolean } }).data.invitationSent, false);
    const directUser = await prisma.user.findUniqueOrThrow({ where: { email: email("direct") }, include: { memberProfile: true } });
    assert.equal(directUser.status, "PENDING_ACTIVATION"); assert.ok(directUser.memberProfile);
    const pendingList = await fetch(`${base}/admin/members?status=pending_activation&search=${encodeURIComponent(directUser.email)}`, { headers: { Authorization: `Bearer ${accessToken}` } });
    assert.equal(pendingList.status, 200);
    const pendingRows = await pendingList.json() as { data: { rows: { email: string; status: string }[] } };
    assert.equal(pendingRows.data.rows[0]?.email, directUser.email); assert.equal(pendingRows.data.rows[0]?.status, "pending_activation");
    assert.equal((await post("/accounts/manual-activation-link", { email: directUser.email })).status, 401);
    const firstLink = await post("/accounts/manual-activation-link", { email: directUser.email }, true);
    assert.equal(firstLink.status, 200);
    assert.equal(firstLink.headers.get("cache-control"), "no-store");
    const firstUrl = ((await firstLink.json()) as { data: { activationUrl: string } }).data.activationUrl;
    const secondLink = await post("/accounts/manual-activation-link", { email: directUser.email }, true);
    assert.equal(secondLink.status, 200);
    const secondUrl = ((await secondLink.json()) as { data: { activationUrl: string } }).data.activationUrl;
    const firstToken = new URL(firstUrl).searchParams.get("token");
    const secondToken = new URL(secondUrl).searchParams.get("token");
    assert.equal((await post("/applications/activate", { token: firstToken, password: "test-password" })).status, 400);
    assert.equal((await post("/applications/activate", { token: secondToken, password: "test-password" })).status, 200);
    assert.equal((await post("/applications/activate", { token: secondToken, password: "test-password" })).status, 400);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: directUser.id } })).emailVerifiedAt, null);
    assert.equal((await post("/auth/login", { email: directUser.email, password: "test-password" })).status, 200);
    assert.equal((await post("/accounts/manual-activation-link", { email: directUser.email }, true)).status, 409);
    const mentor = await post("/accounts", { ...person("mentor"), roleId: mentorRole.id }, true);
    assert.equal(mentor.status, 201, await mentor.clone().text());
    const mentorUser = await prisma.user.findUniqueOrThrow({ where: { email: email("mentor") }, include: { mentorProfile: true, role: true } });
    assert.ok(mentorUser.mentorProfile); assert.equal(mentorUser.role.name, "Mentor");
    const mentorLink = await post("/accounts/manual-activation-link", { email: mentorUser.email }, true);
    assert.equal(mentorLink.status, 200);
    const mentorUrl = ((await mentorLink.json()) as { data: { activationUrl: string } }).data.activationUrl;
    assert.equal((await post("/applications/activate", { token: new URL(mentorUrl).searchParams.get("token"), password: "test-password" })).status, 200);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: mentorUser.id } })).emailVerifiedAt, null);
    failMail = false;
    assert.equal((await post("/auth/login", { email: mentorUser.email, password: "test-password" })).status, 200);
    assert.equal((await post("/accounts", { ...person("mentor"), roleId: mentorRole.id }, true)).status, 409);
    assert.equal((await post("/accounts", { ...person("suspended"), roleId: mentorRole.id }, true)).status, 201);
    const suspended = await prisma.user.findUniqueOrThrow({ where: { email: email("suspended") } });
    const suspendedToken = invitation(suspended.email);
    await prisma.accountActivationToken.update({ where: { tokenHash: createHash("sha256").update(suspendedToken).digest("hex") }, data: { expiresAt: new Date(Date.now() - 1000) } });
    assert.equal((await post("/applications/activate", { token: suspendedToken, password: "test-password" })).status, 400);
    assert.equal((await post("/accounts/resend-invitation", { email: suspended.email }, true)).status, 200);
    const currentToken = invitation(suspended.email);
    await prisma.user.update({ where: { id: suspended.id }, data: { status: "SUSPENDED" } });
    assert.equal((await post("/applications/activate", { token: currentToken, password: "test-password" })).status, 400);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: suspended.id } })).status, "SUSPENDED");
    assert.equal((await prisma.accountActivationToken.findUniqueOrThrow({ where: { tokenHash: createHash("sha256").update(currentToken).digest("hex") } })).usedAt, null);
  } finally {
    server.close();
    await prisma.membershipApplication.deleteMany({ where: { applicantEmail: { in: emails } } });
    const testUsers = await prisma.user.findMany({ where: { email: { in: emails } }, select: { id: true } });
    await prisma.auditLog.deleteMany({ where: { actorUserId: { in: testUsers.map((user) => user.id) } } });
    await prisma.user.deleteMany({ where: { email: { in: emails } } });
    if (oldActivationUrl === undefined) delete process.env.ACTIVATION_URL; else process.env.ACTIVATION_URL = oldActivationUrl;
    await prisma.$disconnect();
    mail = [];
  }
});
